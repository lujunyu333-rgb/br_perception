def sky_grid_positions():
    """
    返回 12 个天空方块位置 [(row, col, color)], color: 1=红朝上, 2=蓝朝上。
    规则(4.1.4): 5×5 网格中心空; 只放 r+c 为偶数的棋盘格(25格中13格, 去掉中心=12格);
    颜色沿中心列镜像: (r,c) 与 (r,4-c) 反色; 中心列恰 2 格(r=0,4), 一红一蓝。
    """
    base = {}   # (r,c) -> color, 只对 c<=2 的半侧直接指定
    for r in range(5):
        for c in range(5):
            if (r + c) % 2 == 1 or (r == 2 and c == 2):
                continue
            if c == 2:                       # 中心列镜像=自身, 直接指定
                base[(r, c)] = 1 if r == 0 else 2
            elif c < 2:                      # 左半侧统一红朝上, 右半侧镜像取蓝
                base[(r, c)] = 1
    out = []
    for (r, c), col in base.items():
        out.append([r, c, col])
        mc = 4 - c
        if mc != c:
            out.append([r, mc, 3 - col])     # 取反色
    out.sort(key=lambda p: (p[0], p[1]))
    return out

